/**
 * Per-wave speed/timer parameters, ported from the Robotron 2084 ROM's
 * wave-init routine (CPU $2B7C; REVERSE.md flat $6B7C) and its 12 tables
 * at CPU $2C20 (43 bytes each: header, min, max, then waves 1-40).
 *
 * This is where the operator DIFFICULTY OF PLAY (0-10, CMOS $CC14) acts.
 * Difficulty never changes enemy counts; it nudges each of these 12 values
 * away from its wave-table entry by round(value * |d-5| * (hdr & $1F) / 256),
 * in the direction given by sign(d-5) XOR hdr bit 7, then clamps to
 * [min, max]. Below 5 the game snaps back to 5 from wave 14, or from wave 5
 * while the player still holds 3+ lives. Waves past 40 cycle 21-40.
 *
 * Verified against MAME: per-wave RAM ($BE5E-$BE67) captured with a bot at
 * difficulties 0/2/3/5/7/8/10 (waves 1-32) matched this model on all 186
 * captured waves (robotron-re tools/difficulty_probe.lua, wave_params.py).
 * Table bytes generated from the ROM — do not hand-edit.
 */

export interface WaveParams {
    /** $BE5C: grunt re-arm bound: each grunt waits prng_bounded(this) 4-frame ticks per step ($79CE) */
    gruntStepBound: number;
    /** $BE5D: floor for $BE5C under the kill speed-up and in-wave ramp; restored on death ($7133) */
    gruntStepFloor: number;
    /** $BE5E: children per spheroid/quark = ceil(prng_le(this) / 2) ($5193, $8B66) */
    childCountBound: number;
    /** $BE5F: enforcer fires every prng_le(this) 3-frame passes ($536D, $5408) */
    enforcerShotTimer: number;
    /** $BE60: spheroid waits prng_le(this) 10-frame cycles, then drops every prng_le(this/4) 16-frame cycles ($518B, $51DB) */
    spheroidDropTimer: number;
    /** $BE61: hulk movement timer (frames per step) ($4098) */
    hulkStepFrames: number;
    /** $BE62: brain fires a cruise missile every prng_le(this) brain steps ($5B46, $6008) */
    brainMissileTimer: number;
    /** $BE63: brain movement timer (frames per step) ($5C9C) */
    brainStepFrames: number;
    /** $BE64: tank fires every this many 2-frame passes ($8CE7, $8E4A) */
    tankShotTimer: number;
    /** $BE65: tank shell velocity = offset to aim point x this / 8192 per frame ($8E98) */
    tankShellSpeed: number;
    /** $BE66: quark waits prng_le(this) 15-frame cycles, then drops a tank every prng_le(this/2+1) 3-frame passes ($8B5E, $8C24) */
    quarkDropTimer: number;
    /** $BE67: quark speed per axis = prng_le(this) / 32 px per frame, re-rolled every 1-32 passes ($8B82) */
    quarkSpeed: number;
}

