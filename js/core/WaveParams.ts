/**
 * Per-wave speed/timer parameters, ported from the Robotron 2084 ROM's
 * wave-init routine (CPU $2B7C; REVERSE.md flat $6B7C) and its 12 tables
 * at CPU $2C20 (43 bytes each: header, min, max, then waves 1-40).
 *
 * This is where the operator DIFFICULTY OF PLAY (0-10, CMOS $CC14) acts.
 * Difficulty never changes enemy counts; it nudges each of these 12 values
 * away from its wave-table entry by round(value * |d-5| * (hdr & $1F) / 256),
 * in the direction given by sign(d-5) XOR hdr bit 7, then clamps to
 * [min, max]. Below 5 the game snaps back to 5 from wave 14, or from wave 5
 * while the player still holds 3+ lives. Waves past 40 cycle 21-40.
 *
 * Verified against MAME: per-wave RAM ($BE5E-$BE67) captured with a bot at
 * difficulties 0/2/3/5/7/8/10 (waves 1-32) matched this model on all 186
 * captured waves (robotron-re tools/difficulty_probe.lua, wave_params.py).
 * Table bytes generated from the ROM — do not hand-edit.
 */

export interface WaveParams {
    /** $BE5C: grunt re-arm timer: each step waits PRNG-bounded(this) frames (flat $39E6) */
    gruntStepBound: number;
    /** $BE5D: paired with $BE5C; restored into it on player death (flat $3130) — role not fully traced */
    gruntStepFloor: number;
    /** $BE5E: PRNG bound for how many enforcers a spheroid emits before retiring */
    enforcersPerSpheroid: number;
    /** $BE5F: PRNG bound gating enforcer bullet spawns (lower = more shots) */
    enforcerShotChance: number;
    /** $BE60: enforcer bullet speed/timer bound */
    enforcerShotTimer: number;
    /** $BE61: hulk movement timer (frames per step) */
    hulkStepFrames: number;
    /** $BE62: PRNG bound for spheroid timers */
    spheroidTimer: number;
    /** $BE63: brain movement timer (frames per step) */
    brainStepFrames: number;
    /** $BE64: enforcer/tank child timer after spawn */
    childSpawnTimer: number;
    /** $BE65: quark/tank fire velocity scale (higher = faster) */
    quarkShotScale: number;
    /** $BE66: spheroid spawn-mode period bound */
    spheroidSpawnPeriod: number;
    /** $BE67: quark position/init param */
    quarkInitParam: number;
}

