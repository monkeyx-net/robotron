/**
 * Per-wave electrode look, from the Robotron 2084 ROM: wave-init ($2A21) picks one
 * of 9 shapes ($3B05 descriptors) from a 10-wave table at $2A4B, so the look repeats
 * every 10 waves. Each look has 3 frames, one char per pixel ('#' lit): frame 0 is the
 * resting shape, and a destroyed electrode shows frames 0, 1, 2 for `hold` frames each
 * (6, 3, 2) before it is erased ($7AA9, $3AD9/$3AE0).
 * Every lit pixel draws in palette entry `entry`, which the ROM colour-cycles
 * (ColorCycles.ts); checked frame by frame in MAME (robotron-re
 * tools/electrode_probe.lua). Waves ending in 7 or 9 never have electrodes.
 *
 * Generated by robotron-re tools/gen_electrodes_ts.py — do not hand-edit.
 */

export interface ElectrodeFrame {
    /** frames this one shows for while the electrode dies */
    hold: number;
    rows: string[];
}

export interface ElectrodeLook {
    /** palette entry the electrodes draw in (row 1 of the $2A4B table) */
    entry: number;
    frames: ElectrodeFrame[];
}

