export const DEFAULT_DIFFICULTY = 5;

/**
 * Parameters for a 1-based wave at operator difficulty 0-10. `lives` is the
 * player's remaining men (the ROM keeps easy settings below 5 past wave 4
 * only once the player is down to fewer than 3).
 */
export function getWaveParams(wave: number, difficulty: number = DEFAULT_DIFFICULTY, lives: number = 3): WaveParams {
    let b = Math.max(0, Math.min(10, Math.round(difficulty)));
    if (b < 5) {
        if (wave >= 14) b = 5;
        if (wave >= 5 && lives >= 3) b = 5;
    }
    const d = b - 5;
    let w = Math.max(1, wave);
    while (w > 40) w -= 20;

    const out = {} as WaveParams;
    TABLES.forEach((t, i) => {
        const v = t.waves[w - 1];
        const p = v * ((Math.abs(d) * (t.hdr & 0x1F)) & 0xFF);
        const delta = (p >> 8) + ((p >> 7) & 1);   // MUL then ADCA #0 (round)
        const negative = ((d & 0xFF) ^ t.hdr) & 0x80;
        let a: number;
        if (negative) {
            a = v - delta;
            if (a < 0) a = t.min;
        } else {
            a = v + delta;
            if (a > 0xFF) a = t.max;
        }
        out[NAMES[i]] = Math.max(t.min, Math.min(t.max, a));
    });
    return out;
}
